/* Document extension color */
export function extColor(ext: string): string {
  const map: Record<string, string> = {
    pdf: "#d05555",
    docx: "#2f6bff",
    doc: "#2f6bff",
    png: "#7a5af8",
    jpg: "#7a5af8",
    xlsx: "#2f9e77",
    csv: "#2f9e77",
    txt: "#5d6b8c",
  };
  return map[ext.toLowerCase()] ?? "#5d6b8c";
}

export function fmtKb(kb: number): string {
  if (kb >= 1024) return (kb / 1024).toFixed(1) + " MB";
  return Math.round(kb) + " KB";
}

/** Trigger a real browser download of a demo document payload. */
export function downloadDemo(name: string, title: string) {
  const body = [
    "LAWFLOW CRM — DEMO DOCUMENT",
    "============================",
    "",
    title,
    "",
    "This is a simulated document preview generated by the LawFlow CRM demo.",
    "In a production deployment this file would be streamed from encrypted",
    "object storage with an audit-logged, access-controlled download URL.",
    "",
    "Confidential — attorney/client privileged.",
  ].join("\n");
  const blob = new Blob([body], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}
