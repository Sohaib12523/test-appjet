/* Entity lookup helpers bound to the live DB */
export function useLookups() {
  const { db } = useStore();
  return useMemo(
    () => ({
      user: (id?: string) => db.users.find((u) => u.id === id),
      userName: (id?: string) => db.users.find((u) => u.id === id)?.name ?? "—",
      matter: (id?: string) => db.matters.find((m) => m.id === id),
      matterName: (id?: string) =>
        id ? db.matters.find((m) => m.id === id)?.name ?? "—" : "—",
      client: (id?: string) => db.clients.find((c) => c.id === id),
      clientName: (id?: string) =>
        id ? db.clients.find((c) => c.id === id)?.name ?? "—" : "—",
      lead: (id?: string) => db.leads.find((l) => l.id === id),
      leadName: (id?: string) => {
        const l = db.leads.find((x) => x.id === id);
        return l ? `${l.firstName} ${l.lastName}` : "—";
      },
    }),
    [db]
  );
}

/* Invoice math */
export function invTotal(inv: Invoice): number {
  return inv.items.reduce((s, i) => s + i.amount, 0);
}
export function invPaid(inv: Invoice): number {
  return inv.payments.reduce((s, p) => s + p.amount, 0);
}
export function invBal(inv: Invoice): number {
  return Math.max(invTotal(inv) - invPaid(inv), 0);
}

/* Derived task status (adds "Overdue") */
export function effectiveTaskStatus(t: TaskItem): string {
  if (t.status === "Completed") return "Completed";
  if (isPastDate(t.dueDate)) return "Overdue";
  return t.status;
}

